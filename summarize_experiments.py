"""Summarize recursively collected deterministic evaluation results."""

import argparse
import csv
import json
import os
from collections import defaultdict

import numpy as np


PAPER_BENCHMARKS = {
    "tddrl_ssr": {"ssr": 5.03, "energy_kj": 12.4, "see": 40.8},
    "ttd3_ssr": {"ssr": 6.05, "energy_kj": 12.7, "see": 48.2},
    "tddrl_see": {"ssr": 4.68, "energy_kj": 11.2, "see": 39.4},
    "ttd3_see": {"ssr": 5.39, "energy_kj": 11.2, "see": 48.4},
}


def main(args):
    rows = []
    for root, _, files in os.walk(args.root):
        if 'evaluation_summary.json' not in files:
            continue
        with open(os.path.join(root, 'evaluation_summary.json')) as handle:
            summary = json.load(handle)['summary']
        rows.append({
            'reward': summary['reward'], 'seed': summary.get('seed', ''),
            'mean_ssr': summary['mean_ssr'], 'std_ssr': summary['std_ssr'],
            'mean_energy_kj': summary['mean_energy_kj'], 'std_energy_kj': summary['std_energy_kj'],
            'mean_see': summary['mean_see'], 'std_see': summary['std_see'],
        })
    rows.sort(key=lambda row: (row['reward'], str(row['seed'])))
    os.makedirs(args.output_dir, exist_ok=True)
    detail_path = os.path.join(args.output_dir, 'reward_comparison.csv')
    fields = ['reward', 'seed', 'mean_ssr', 'std_ssr', 'mean_energy_kj', 'std_energy_kj', 'mean_see', 'std_see']
    with open(detail_path, 'w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader(); writer.writerows(rows)

    grouped = defaultdict(lambda: defaultdict(list))
    for row in rows:
        for metric in ('mean_ssr', 'mean_energy_kj', 'mean_see'):
            grouped[row['reward']][metric].append(float(row[metric]))
    grouped_rows = []
    for reward, values in sorted(grouped.items()):
        grouped_rows.append({
            'reward': reward, 'num_runs': len(values['mean_ssr']),
            'SSR_mean': np.mean(values['mean_ssr']), 'SSR_std': np.std(values['mean_ssr']),
            'Energy_mean': np.mean(values['mean_energy_kj']), 'Energy_std': np.std(values['mean_energy_kj']),
            'SEE_mean': np.mean(values['mean_see']), 'SEE_std': np.std(values['mean_see']),
        })
    grouped_path = os.path.join(args.output_dir, 'reward_comparison_grouped.csv')
    grouped_fields = ['reward', 'num_runs', 'SSR_mean', 'SSR_std', 'Energy_mean', 'Energy_std', 'SEE_mean', 'SEE_std']
    with open(grouped_path, 'w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=grouped_fields)
        writer.writeheader(); writer.writerows(grouped_rows)
    print('Reward comparison (generated evaluation results)')
    print('reward\tnum_runs\tSSR_mean\tSSR_std\tEnergy_mean\tEnergy_std\tSEE_mean\tSEE_std')
    for row in grouped_rows:
        print('{reward}\t{num_runs}\t{SSR_mean:.4f}\t{SSR_std:.4f}\t{Energy_mean:.4f}\t{Energy_std:.4f}\t{SEE_mean:.4f}\t{SEE_std:.4f}'.format(**row))
    print('Published reference numbers (not generated by these runs):')
    for name, values in PAPER_BENCHMARKS.items():
        print('{}: {}'.format(name, values))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', default='data/storage')
    parser.add_argument('--output-dir', default='data/storage/summary')
    main(parser.parse_args())

